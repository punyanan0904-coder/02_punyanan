# โจทย์ข้อที่ 1: คำนวณคะแนนเฉลี่ย 3 วิชา
# Input: บรรทัดที่ 1-3 คะแนนวิชาที่ 1, 2, 3 (จำนวนเต็ม)
# Output: คะแนนเฉลี่ย
# ==========================================


s1 = int(input("คะเเนนวิชาที่1:"))
s2 = int(input("คะเเนนวิชาที่2:"))
s3 = int(input("คะเเนนวิชาที่3:"))
result = (s1 + s2 + s3)/3
print(result)
